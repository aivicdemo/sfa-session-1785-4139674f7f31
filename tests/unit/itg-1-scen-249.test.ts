import { calculateProcessComplianceScore } from '../../src/logic/it-1-br-2-1-1-1';

describe('AIエージェント推論精度の自動監視とアラート機能', () => {
  // SCEN-249
  test('標準プロセス遵守度スコア計算機能 - 乖離度計算時に小数点以下の端数が生じるとき正しく丸められる', () => {
    // 手順: 乖離度計算機能に対して、計算結果が小数点以下3桁以上になるテストケースを入力する
    // 計算条件例: 標準プロセスステップ5段階中、実行完了3段階、実行部分的1段階、未実行1段階
    // 遵守度 = (完了段階数 + 部分的実行段階数×0.5) / 総段階数
    // = (3 + 1×0.5) / 5 = 3.5 / 5 = 0.7 = 70%
    // より端数が生じるケース: 実行完了4段階、部分的1段階
    // = (4 + 1×0.5) / 6 = 4.5 / 6 = 0.75 = 75%
    // さらに複雑: 実行完了4段階、部分的2段階、未実行4段階 (計10段階)
    // = (4 + 2×0.5) / 10 = 5 / 10 = 0.5 = 50%
    // 端数3桁以上: 実行完了2段階、部分的1段階、未実行3段階 (計6段階)
    // = (2 + 1×0.5) / 6 = 2.5 / 6 = 0.41666... = 41.666...%
    
    const completedSteps = 2;
    const partialSteps = 1;
    const totalSteps = 6;

    const score = calculateProcessComplianceScore({
      completedSteps,
      partialSteps,
      totalSteps,
    });

    // 期待結果: 乖離度スコアが小数点以下第2位で四捨五入されて返される
    // 計算: (2 + 1×0.5) / 6 × 100 = 2.5 / 6 × 100 = 41.66666...%
    // 小数点以下第2位で四捨五入: 41.67%
    expect(score).toBe(41.67);
  });
});